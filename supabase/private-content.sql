create or replace function public.love_adjust_stat(stat_id text, delta_value integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	clean_id text;
	current_value bigint;
	new_value bigint;
	saved_stat jsonb;
begin
	actor_cat := public.love_current_cat();
	clean_id := lower(trim(coalesce(stat_id, '')));

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	select case
		when coalesce(value, '') ~ '^\d+$' then value::bigint
		else 0
	end
	into current_value
	from public.love_stats
	where id = clean_id;

	if not found then
		raise exception 'stat not found';
	end if;

	new_value := greatest(0, current_value + coalesce(delta_value, 0));

	update public.love_stats
	set value = new_value::text,
		mode = null,
		target_date = null,
		updated_at = now()
	where id = clean_id
	returning to_jsonb(public.love_stats.*) into saved_stat;

	return saved_stat;
end;
$$;

