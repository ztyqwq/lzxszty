create or replace function public.love_perform_cat_action(action_name text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	target_cat text;
	mood_delta integer;
	affection_delta integer;
	updated_cat jsonb;
begin
	actor_cat := public.love_current_cat();

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	if action_name = 'feed' then
		target_cat := case when actor_cat = 'black' then 'white' else 'black' end;
		mood_delta := 8;
		affection_delta := 6;
	elsif action_name = 'meow' then
		target_cat := actor_cat;
		mood_delta := 5;
		affection_delta := 4;
	else
		raise exception 'unknown action';
	end if;

	update public.love_cats
	set mood = least(100, mood + mood_delta),
		affection = least(100, affection + affection_delta),
		updated_at = now()
	where id = target_cat
	returning to_jsonb(public.love_cats.*) into updated_cat;

	return updated_cat;
end;
$$;

create or replace function public.love_add_meow_message(message_body text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	clean_body text;
	inserted_message jsonb;
begin
	actor_cat := public.love_current_cat();
	clean_body := trim(coalesce(message_body, ''));

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	if clean_body = '' then
		raise exception 'message is empty';
	end if;

	insert into public.love_meow_messages (author, body)
	values (actor_cat, clean_body)
	returning to_jsonb(public.love_meow_messages.*) into inserted_message;

	return inserted_message;
end;
$$;

create or replace function public.love_save_post(
	post_slug text,
	post_title text,
	post_summary text,
	post_body text,
	post_tags text[] default '{}',
	post_hero_image_path text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	clean_slug text;
	clean_title text;
	existing_author text;
	post_exists boolean;
	saved_post jsonb;
begin
	actor_cat := public.love_current_cat();
	clean_slug := lower(trim(coalesce(post_slug, '')));
	clean_slug := regexp_replace(clean_slug, '[^a-z0-9-]+', '-', 'g');
	clean_slug := regexp_replace(clean_slug, '-+', '-', 'g');
	clean_slug := trim(both '-' from clean_slug);
	clean_title := trim(coalesce(post_title, ''));

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	if clean_slug = '' then
		raise exception 'post slug is empty';
	end if;

	if clean_title = '' then
		raise exception 'post title is empty';
	end if;

	select author
	into existing_author
	from public.love_posts
	where slug = clean_slug;
	post_exists := found;

	if post_exists then
		if existing_author is distinct from actor_cat then
			raise exception 'only the author can edit this post';
		end if;

		update public.love_posts
		set title = clean_title,
			summary = nullif(trim(coalesce(post_summary, '')), ''),
			body = coalesce(post_body, ''),
			tags = coalesce(post_tags, '{}'),
			hero_image_path = nullif(trim(coalesce(post_hero_image_path, '')), ''),
			updated_at = now()
		where slug = clean_slug
		returning to_jsonb(public.love_posts.*) into saved_post;
	else
		insert into public.love_posts (
			slug,
			title,
			summary,
			body,
			tags,
			author,
			hero_image_path,
			published_at
		)
		values (
			clean_slug,
			clean_title,
			nullif(trim(coalesce(post_summary, '')), ''),
			coalesce(post_body, ''),
			coalesce(post_tags, '{}'),
			actor_cat,
			nullif(trim(coalesce(post_hero_image_path, '')), ''),
			current_date
		)
		returning to_jsonb(public.love_posts.*) into saved_post;
	end if;

	return saved_post;
end;
$$;

create or replace function public.love_delete_post(post_slug text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	existing_author text;
	clean_slug text;
begin
	actor_cat := public.love_current_cat();
	clean_slug := lower(trim(coalesce(post_slug, '')));

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	select author
	into existing_author
	from public.love_posts
	where slug = clean_slug;

	if not found then
		raise exception 'post not found';
	end if;

	if existing_author is distinct from actor_cat then
		raise exception 'only the author can delete this post';
	end if;

	delete from public.love_posts
	where slug = clean_slug;

	return clean_slug;
end;
$$;

create or replace function public.love_save_stat(
	stat_id text,
	left_text text default '',
	right_text text default '',
	stat_sort_order integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
	actor_cat text;
	clean_id text;
	clean_left text;
	clean_right text;
	next_order integer;
	saved_stat jsonb;
begin
	actor_cat := public.love_current_cat();
	clean_id := lower(trim(coalesce(stat_id, '')));
	clean_id := regexp_replace(clean_id, '[^a-z0-9-]+', '-', 'g');
	clean_id := regexp_replace(clean_id, '-+', '-', 'g');
	clean_id := trim(both '-' from clean_id);
	clean_left := regexp_replace(trim(coalesce(left_text, '')), '[\r\n]+', ' ', 'g');
	clean_right := regexp_replace(trim(coalesce(right_text, '')), '[\r\n]+', ' ', 'g');

	if actor_cat is null then
		raise exception 'not allowed';
	end if;

	if clean_id = '' then
		raise exception 'stat id is empty';
	end if;

	if stat_sort_order is null then
		select coalesce(max(sort_order), 0) + 10
		into next_order
		from public.love_stats;
	else
		next_order := stat_sort_order;
	end if;

	insert into public.love_stats (
		id,
		label,
		value,
		suffix,
		size,
		mode,
		target_date,
		sort_order
	)
	values (
		clean_id,
		clean_left,
		'0',
		clean_right,
		'medium',
		null,
		null,
		next_order
	)
	on conflict (id) do update
	set label = excluded.label,
		suffix = excluded.suffix,
		sort_order = excluded.sort_order,
		updated_at = now()
	returning to_jsonb(public.love_stats.*) into saved_stat;

	return saved_stat;
end;
$$;

